const QUALITY_LABELS: Record<string, string> = {
  x_low: 'Extra Low',
  low: 'Low',
  medium: 'Medium',
  high: 'High',
}

/** `hfc_female` → `Hfc Female`. */
function titleCase(name: string): string {
  return name
    .split('_')
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ')
}

/** `en_GB-alan-low` → Alan (Low), English (Great Britain). */
function piperVoice(id: string): VoiceInfo {
  const [locale = '', name = '', quality = ''] = id.split('-')
  const [language = '', region = ''] = locale.split('_')
  return {
    id,
    label: `${titleCase(name)} (${QUALITY_LABELS[quality] ?? quality})`,
    language: `${LANGUAGE_NAMES[language] ?? language} (${REGION_NAMES[region] ?? region})`,
  }
}

export const PIPER_VOICES: VoiceInfo[] = PIPER_VOICE_IDS.map(piperVoice)
