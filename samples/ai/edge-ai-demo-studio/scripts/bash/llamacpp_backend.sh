# Helpers for selecting, installing and activating the multiserve engine's llama.cpp
# backend (SYCL or Vulkan). Meant to be sourced, not executed.

# --- Constants ---------------------------------------------------------------

# llama.cpp release shipped with the multiserve engine.
LLAMACPP_VERSION="${LLAMACPP_VERSION:-b11540}"
LLAMACPP_RELEASE_BASE_URL="https://github.com/ggml-org/llama.cpp/releases/download"

# The SYCL build links against the Intel SYCL runtime, which this workers/pyproject.toml
# group installs from wheels into workers/.venv/lib (not the oneAPI Toolkit). b11540 was
# linked against oneAPI 2026.1 and runs on those 2026.0 wheels. When bumping
# LLAMACPP_VERSION, re-read `readelf -d libggml-sycl.so` and update SYCL_RUNTIME_LIBS.
LLAMACPP_SYCL_GROUP="llamacpp-sycl"

# Runtime libraries libggml-sycl.so links against (from `readelf -d`).
SYCL_RUNTIME_LIBS=(
  libsycl.so.9
  libmkl_sycl_blas.so.6
  libmkl_intel_ilp64.so.3
  libmkl_tbb_thread.so.3
  libmkl_core.so.3
  libdnnl.so.3
  libtbb.so.12
  # Intel compiler runtime (intel-cmplr-lib-rt)
  libimf.so
  libsvml.so
  libirng.so
  libintlc.so.5
)

# Runtime libraries from the GPU driver stack (install_dependencies.sh), not the wheels.
SYCL_DRIVER_LIBS=(
  libze_loader.so.1
)

# Stored with the multiserve engine, the only llama.cpp user, so it travels with it
# through packaging and export bundles.
LLAMACPP_BACKEND_CONFIG_NAME="workers/engines/multiserve/.llamacpp-backend"

# --- Paths -------------------------------------------------------------------

# Repo root from this file's location: <root>/scripts/bash/ in-repo, <root>/scripts/ when packaged.
_lb_resolve_repo_root() {
    if [ -n "${LLAMACPP_BACKEND_REPO_ROOT:-}" ]; then
        echo "$LLAMACPP_BACKEND_REPO_ROOT"
        return 0
    fi

    local self_dir
    self_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

    if [ "$(basename "$self_dir")" = "bash" ]; then
        (cd "$self_dir/../.." && pwd)
    else
        (cd "$self_dir/.." && pwd)
    fi
}

LLAMACPP_BACKEND_REPO_ROOT="$(_lb_resolve_repo_root)"
# A caller may point this at a different file before sourcing - the Electron app
# does that when the install directory turns out to be read-only.
LLAMACPP_BACKEND_CONFIG_FILE="${LLAMACPP_BACKEND_CONFIG_FILE:-$LLAMACPP_BACKEND_REPO_ROOT/$LLAMACPP_BACKEND_CONFIG_NAME}"

# Directory of the multiserve engine, or empty when this build does not ship it
# (an export bundle without the LLM engine has nothing to configure).
LLAMACPP_MULTISERVE_DIR="$LLAMACPP_BACKEND_REPO_ROOT/workers/engines/multiserve"

# The shared worker uv workspace and the library directory its environment
# gets from the SYCL runtime wheels.
LLAMACPP_WORKERS_DIR="$LLAMACPP_BACKEND_REPO_ROOT/workers"
LLAMACPP_SYCL_RUNTIME_DIR="$LLAMACPP_WORKERS_DIR/.venv/lib"

lb_multiserve_present() {
    [ -d "$LLAMACPP_MULTISERVE_DIR" ]
}

# --- Config file -------------------------------------------------------------

# Load the persisted backend selection into the current shell.
# Sets: LLAMACPP_BACKEND, LLAMACPP_SYCL_PRECISION.
# Returns 1 (leaving the defaults in place) when no config file exists yet.
lb_load_config() {
    LLAMACPP_BACKEND="${LLAMACPP_BACKEND:-vulkan}"
    LLAMACPP_SYCL_PRECISION="${LLAMACPP_SYCL_PRECISION:-fp16}"

    if [ ! -f "$LLAMACPP_BACKEND_CONFIG_FILE" ]; then
        return 1
    fi

    # Only accept the keys we own; the file is generated, but be defensive.
    local key value
    while IFS='=' read -r key value; do
        case "$key" in
            LLAMACPP_BACKEND) LLAMACPP_BACKEND="$value" ;;
            LLAMACPP_SYCL_PRECISION) LLAMACPP_SYCL_PRECISION="$value" ;;
        esac
    done < <(grep -E '^(LLAMACPP_BACKEND|LLAMACPP_SYCL_PRECISION)=' "$LLAMACPP_BACKEND_CONFIG_FILE" 2>/dev/null || true)

    export LLAMACPP_BACKEND LLAMACPP_SYCL_PRECISION
    return 0
}

# lb_save_config <backend> [precision]
lb_save_config() {
    local backend="$1"
    local precision="${2:-fp16}"

    {
        echo "# Generated by setup.sh - selects the llama.cpp build used by the"
        echo "# multiserve engine. Re-run ./setup.sh to change it."
        echo "LLAMACPP_BACKEND=$backend"
        if [ "$backend" = "sycl" ]; then
            echo "LLAMACPP_SYCL_PRECISION=$precision"
        fi
    } > "$LLAMACPP_BACKEND_CONFIG_FILE"

    LLAMACPP_BACKEND="$backend"
    LLAMACPP_SYCL_PRECISION="$precision"
    export LLAMACPP_BACKEND LLAMACPP_SYCL_PRECISION
}

# --- SYCL runtime ------------------------------------------------------------

# lb_install_sycl_runtime <uv> - install the runtime wheels into workers/.venv.
# --inexact keeps what the workers installed there; --frozen takes the
# committed lock as it is.
lb_install_sycl_runtime() {
    "$1" sync --frozen --inexact --project "$LLAMACPP_WORKERS_DIR" --only-group "$LLAMACPP_SYCL_GROUP"
}

# Put the runtime on LD_LIBRARY_PATH, ahead of any oneAPI environment a user
# sourced themselves. Returns 1 when it is not installed.
lb_activate_sycl_runtime() {
    [ -e "$LLAMACPP_SYCL_RUNTIME_DIR/${SYCL_RUNTIME_LIBS[0]}" ] || return 1
    case ":${LD_LIBRARY_PATH:-}:" in
        *":$LLAMACPP_SYCL_RUNTIME_DIR:"*) ;;
        *) export LD_LIBRARY_PATH="$LLAMACPP_SYCL_RUNTIME_DIR${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}" ;;
    esac
}

# Locate a shared object either through LD_LIBRARY_PATH or the ldconfig cache.
_lb_find_lib() {
    local name="$1"
    local dir

    local oldIFS="$IFS"
    IFS=':'
    for dir in ${LD_LIBRARY_PATH:-}; do
        IFS="$oldIFS"
        if [ -n "$dir" ] && [ -e "$dir/$name" ]; then
            return 0
        fi
        IFS=':'
    done
    IFS="$oldIFS"

    if command -v ldconfig >/dev/null 2>&1; then
        ldconfig -p 2>/dev/null | grep -qF "$name" && return 0
    fi

    return 1
}

# lb_verify_sycl_runtime <libggml-sycl.so> - check the installed runtime can load this build.
# `ldd -r` binds every symbol, so a too-old runtime fails here, not at the first model load.
lb_verify_sycl_runtime() {
    local library="$1"
    local failed=false
    local lib

    for lib in "${SYCL_RUNTIME_LIBS[@]}"; do
        if [ -e "$LLAMACPP_SYCL_RUNTIME_DIR/$lib" ]; then
            echo "  ✓ $lib"
        else
            echo "  ✗ $lib not found in $LLAMACPP_SYCL_RUNTIME_DIR"
            failed=true
        fi
    done

    for lib in "${SYCL_DRIVER_LIBS[@]}"; do
        if _lb_find_lib "$lib"; then
            echo "  ✓ $lib"
        else
            # Driver-provided, not part of the runtime wheels: warn but do not
            # fail, the GPU driver installer covers these.
            echo "  ! $lib not found - install the Intel GPU drivers (level-zero)"
        fi
    done

    if [ "$failed" = true ]; then
        return 1
    fi

    local problems
    problems="$(
        LD_LIBRARY_PATH="$LLAMACPP_SYCL_RUNTIME_DIR${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}" \
            ldd -r "$library" 2>&1 | grep -E 'not found|undefined symbol|error while loading' || true
    )"
    if [ -n "$problems" ]; then
        echo "  ✗ $(basename "$library") cannot load on this runtime:"
        echo "$problems"
        return 1
    fi
    echo "  ✓ $(basename "$library") resolves every library and symbol"
    return 0
}

# SYCL build flavour: FP16 unless LLAMACPP_SYCL_PRECISION_OVERRIDE=fp32. Upstream recommends
# FP16 in most cases; it needs the fp16 aspect, which every SYCL-supported Intel GPU has.
lb_detect_sycl_precision() {
    echo "${LLAMACPP_SYCL_PRECISION_OVERRIDE:-fp16}"
}

# --- llama.cpp release selection ---------------------------------------------

# lb_llamacpp_asset <backend> [precision]
lb_llamacpp_asset() {
    local backend="$1"
    local precision="${2:-fp16}"

    if [ "$backend" = "sycl" ]; then
        echo "llama-${LLAMACPP_VERSION}-bin-ubuntu-sycl-${precision}-x64.tar.gz"
    else
        echo "llama-${LLAMACPP_VERSION}-bin-ubuntu-vulkan-x64.tar.gz"
    fi
}

# lb_llamacpp_url <backend> [precision]
lb_llamacpp_url() {
    echo "$LLAMACPP_RELEASE_BASE_URL/$LLAMACPP_VERSION/$(lb_llamacpp_asset "$@")"
}

# lb_engine_dir <backend> - directory name expected by multiserve's
# LlamaCPPManager (engine/llama.cpp-<backend>).
lb_engine_dir() {
    echo "llama.cpp-$1"
}
